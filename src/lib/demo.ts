export const demoEntries: VocabularyEntry[] = rows.map((r, i) => ({
  id: `demo-${i}`,
  expression: r[0],
  definition_fr: r[1],
  definition_zh: r[2],
  main_chunk: r[3],
  example_fr: r[4],
  example_type: "Exemple pédagogique",
  level: r[5],
  register: r[6],
  tags: [i > 16 ? "expression idiomatique" : "société"],
  other_chunks: r[7]
    ? r[7].split("|").map((text, j) => ({ id: `chunk-${i}-${j}`, text }))
    : [],
}));
export const normalize = (value: string) =>
  value
    .trim()
    .toLocaleLowerCase("fr")
    .replace(/[’‘]/g, "'")
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "");
export function findDemo(value: string) {
  return demoEntries.find((e) => normalize(e.expression) === normalize(value));
}
